let currentLang = DEFAULT_LANG;

export function getLang() {
  return currentLang;
}

export function t(key, lang = currentLang) {
  const pack = translations[lang] || translations[DEFAULT_LANG];
  return pack[key] ?? translations.en[key] ?? key;
}

export function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const value = t(key, lang);
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'), lang));
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'), lang));
  });

  document.querySelectorAll('[data-i18n-option]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n-option'), lang);
  });

  const path = window.location.pathname || '';
  const isBioPage = /bio\.html$/i.test(path) || document.body?.dataset?.page === 'bio';
  const isStartPage = /start\.html$/i.test(path) || document.body?.dataset?.page === 'start';
  const isCentersPage = /centers\.html$/i.test(path) || document.body?.dataset?.page === 'centers';
  const title = isBioPage
    ? `${t('bio.name', lang)} — ${t('bio.section.story', lang)}`
    : isStartPage
      ? `${t('start.title', lang)} — Avazov Ogabek`
      : isCentersPage
        ? t('centers.metaTitle', lang)
        : t('meta.title', lang);
  const desc = isBioPage
    ? t('bio.tagline', lang)
    : isStartPage
      ? t('start.intro', lang)
      : isCentersPage
        ? t('centers.metaDescription', lang)
        : t('meta.description', lang);
  document.title = title;
  const setMeta = (selector, attr, value) => {
    const el = document.querySelector(selector);
    if (el && value != null) el.setAttribute(attr, value);
  };
  setMeta('meta[name="description"]', 'content', desc);
  setMeta('meta[name="keywords"]', 'content', t('meta.keywords', lang));
  const ogTitle = isCentersPage ? t('centers.metaTitle', lang)
    : isBioPage || isStartPage ? title
      : t('meta.ogTitle', lang);
  const ogDesc = isCentersPage ? t('centers.metaDescription', lang)
    : isBioPage || isStartPage ? desc
      : t('meta.ogDescription', lang);
  setMeta('meta[property="og:title"]', 'content', ogTitle);
  setMeta('meta[property="og:description"]', 'content', ogDesc);
  setMeta('meta[property="og:locale"]', 'content', t('meta.ogLocale', lang));
  setMeta('meta[name="twitter:title"]', 'content', ogTitle);
  setMeta('meta[name="twitter:description"]', 'content', ogDesc);

  document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
    const active = btn.getAttribute('data-lang-btn') === lang;
    btn.classList.toggle('bg-black', active);
    btn.classList.toggle('text-white', active);
    btn.classList.toggle('border-black', active);
    btn.classList.toggle('text-neutral-600', !active);
    btn.classList.toggle('border-neutral-300', !active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });

  window.dispatchEvent(new CustomEvent('echo:langchange', { detail: { lang } }));
}

function resolveInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search || '');
    const fromQuery = (params.get('lang') || '').toLowerCase();
    if (SUPPORTED_LANGS.includes(fromQuery)) return fromQuery;
  } catch (_) {}
  const saved = localStorage.getItem(STORAGE_KEY);
  return SUPPORTED_LANGS.includes(saved) ? saved : DEFAULT_LANG;
}

export function initI18n() {
  applyLanguage(resolveInitialLang());

  document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
    btn.addEventListener('click', () => {
      const next = btn.getAttribute('data-lang-btn');
      applyLanguage(next);
      try {
        const url = new URL(window.location.href);
        url.searchParams.set('lang', next);
        window.history.replaceState({}, '', url);
      } catch (_) {}
    });
  });
}

window.EchoI18n = { t, getLang, applyLanguage, initI18n, SUPPORTED_LANGS, DEFAULT_LANG };
